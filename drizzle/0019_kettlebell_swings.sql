-- 3. The swings' template rows, open from today in the user's own timezone —
-- the day the owner chose (the day this is applied), and "today" is only
-- meaningful in the zone the rest of the app resolves dates in.
INSERT INTO "training_template_entries" (
  "user_id", "day_of_week", "workout_id", "rotation_group", "sort_order", "valid_from"
)
SELECT
  e."user_id", e."day_of_week", k."id", NULL::text, e."sort_order",
  (now() AT TIME ZONE p."timezone")::date
FROM "training_template_entries" e
JOIN "workouts" s ON s."id" = e."workout_id" AND s."user_id" = e."user_id"
JOIN "workouts" k
  ON k."user_id" = e."user_id" AND k."type" = 'kettlebell' AND k."name" = 'Kettlebell Swings'
JOIN "profiles" p ON p."user_id" = e."user_id"
WHERE
  s."name" = 'Skipping Intervals + Core'
  AND s."type" = 'intervals'
  AND e."valid_until" IS NULL
  AND NOT EXISTS (
    SELECT 1 FROM "training_template_entries" n
    WHERE n."user_id" = e."user_id" AND n."day_of_week" = e."day_of_week"
      AND n."workout_id" = k."id"
  );
--> statement-breakpoint

-- 4. The skipping rows closed the day before — where, and only where, a
-- swings row now opens on that weekday. A user step 3 could not serve (no
-- profile, so no timezone) keeps skipping rather than losing the day.
UPDATE "training_template_entries" AS e
SET "valid_until" = n."valid_from" - 1
FROM "workouts" s, "workouts" k, "training_template_entries" n
WHERE
  s."id" = e."workout_id"
  AND s."user_id" = e."user_id"
  AND s."name" = 'Skipping Intervals + Core'
  AND s."type" = 'intervals'
  AND e."valid_until" IS NULL
  AND k."user_id" = e."user_id"
  AND k."type" = 'kettlebell'
  AND k."name" = 'Kettlebell Swings'
  AND n."user_id" = e."user_id"
  AND n."workout_id" = k."id"
  AND n."day_of_week" = e."day_of_week"
  AND n."valid_from" IS NOT NULL;
--> statement-breakpoint

-- 5. The session's time of day moves with it. `workout_times` is keyed by
-- type, and /settings now offers `kettlebell` where it offered `intervals`;
-- a stored intervals time with no kettlebell one is copied across, and the
-- intervals key is left where it is.
UPDATE "profiles"
SET "workout_times" = "workout_times" || jsonb_build_object('kettlebell', "workout_times" -> 'intervals')
WHERE
  jsonb_typeof("workout_times") = 'object'
  AND "workout_times" ? 'intervals'
  AND NOT ("workout_times" ? 'kettlebell');
