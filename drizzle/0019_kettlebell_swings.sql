-- FUEL-130 — kettlebell swings replace the Tue/Thu skipping session.
--
-- Schema, then data, in one file because the data needs the schema.
--
-- ## The columns
--
-- `training_template_entries.valid_from` / `valid_until` are the dates a row
-- schedules on, inclusive, null meaning open. Every existing row is open at
-- both ends, so it resolves exactly as it did. They exist because a past date
-- is RESOLVED against the template rather than read back from a log: the
-- adherence grid, /training's Recent and past dates, and the week export all
-- ask the template what 3 September held. Repointing Tuesday in place would
-- answer with today's workout and orphan every skipping log.
--
-- `workout_exercises.target_total_reps` is the swings' 75, which is not a set
-- count. `takes_load` marks the exercise whose sets write
-- `exercise_sets.load_kg`, dormant since 0008 and first written here.
--
-- All four are additive: null, or false by default, which is what every
-- existing row means. The code already deployed selects explicit columns and
-- never names them.
--
-- ## The data
--
-- For every user whose Tue/Thu is still the open-ended skipping session:
--
--   1. a Kettlebell Swings workout,
--   2. its exercises, as `src/lib/seed/workouts.ts` defines them,
--   3. its template rows, on the same weekdays and in the same sort order,
--      open from the day this runs IN THAT USER'S TIMEZONE,
--   4. the skipping rows closed the day before — only where step 3 put a
--      replacement beside them, so a user is never left with neither,
--   5. the intervals slot time copied to the kettlebell one.
--
-- NOTHING IS DELETED OR RENAMED. The skipping workout keeps its id, name, type
-- and exercises, so every log, set and export line that points at it still
-- reads "Skipping Intervals + Core", and still costs at the rope's MET band.
--
-- Idempotent: each step is guarded on its own result, so a re-run finds the
-- workout, the exercises and the rows already there and the skipping rows
-- already closed, and changes nothing. Every user, owner and demo alike, as
-- 0011 did — a demo's library is the same seed's.
--
-- The literals below are generated by `src/lib/seed/kettlebell-backfill.ts`,
-- and `kettlebell-backfill.test.ts` fails if they stop matching the seed.
-- The seed is authoritative from here on; these are this migration's record
-- of what it wrote.
--
-- Matched by name AND type, because `workouts` has no stable key column: the
-- seed's key never reaches the database.

